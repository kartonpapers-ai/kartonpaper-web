const {JSDOM}=require('jsdom');
const fs=require('fs'),path=require('path'),assert=require('assert/strict');
const root=path.resolve(__dirname,'..');
const flush=()=>new Promise(resolve=>setImmediate(resolve));
(async()=>{
 const dom=new JSDOM(fs.readFileSync(path.join(root,'index.html'),'utf8'),{url:'https://kp.test/',runScripts:'outside-only',pretendToBeVisual:true});
 const w=dom.window,doc=w.document,loads=new Map(),animations=[],timers=new Map();let next=0,fontsReady;
 w.matchMedia=()=>({matches:false,addEventListener(){},removeEventListener(){}});
 w.Image=class{set src(value){this.url=value;}decode(){return new Promise((resolve,reject)=>loads.set(this.url,{resolve,reject}));}};
 w.HTMLImageElement.prototype.decode=()=>Promise.resolve();
 w.Element.prototype.animate=function(frames,options){const a={frames,options,cancel(){},pause(){},play(){}};animations.push(a);return a;};
 Object.defineProperty(doc,'fonts',{value:{ready:new Promise(resolve=>fontsReady=resolve)}});
 w.setTimeout=(fn,ms)=>{const id=++next;timers.set(id,{fn,ms});return id;};w.clearTimeout=id=>timers.delete(id);
 w.eval(fs.readFileSync(path.join(root,'js/hero-editorial.js'),'utf8'));
 const stop=w.KP_EDITORIAL.init({products:[],openCustomizer(){}});
 const selected=()=>doc.querySelector('[data-hero-category][aria-pressed="true"]').dataset.heroCategory;
 const click=category=>doc.querySelector(`[data-hero-category="${category}"]`).click();
 const load=name=>[...loads].find(([url])=>url.includes(name))[1];
 assert.equal(loads.size,6,'Precarga las seis imágenes de escritorio');
 click('bolsas');assert.equal(selected(),'reposteria','Conserva el hero anterior durante la carga');
 load('bolsas-mixed-media').resolve();await flush();
 assert.equal(selected(),'bolsas');
 assert.equal(doc.querySelectorAll('.eh-stage > img[aria-hidden="true"]').length,1,'Conserva una capa de la imagen anterior');
 const fade=animations.find(a=>a.options.duration===800&&a.frames.at(-1).opacity===0);
 assert.ok(fade,'El cambio usa un fundido');fade.onfinish();
 assert.equal(doc.querySelectorAll('.eh-stage > img').length,0);
 assert.ok(!animations.some(a=>a.frames[0].opacity===.35),'No reinicia la opacidad de la nueva foto');
 fontsReady();await flush();
 assert.ok(!animations.some(a=>a.options.duration===2400),'Fuentes tardías no reinician la animación de entrada');
 click('doypack');click('cerveza');load('cerveza-mixed-media').resolve();await flush();
 assert.equal(selected(),'cerveza');load('doypack-mixed-media').resolve();await flush();
 assert.equal(selected(),'cerveza','Una carga anterior no sobreescribe la última selección');
 click('posavasos');load('posavasos-mixed-media').reject(new Error('network'));await flush();
 assert.equal(selected(),'cerveza','Una imagen fallida conserva el hero visible');
 click('gastronomia');stop();load('compostables-kp').resolve();await flush();
 assert.equal(selected(),'cerveza','Una carga pendiente no cambia el hero después de desmontarlo');
 assert.equal(timers.size,0);assert.equal(doc.querySelectorAll('.eh-stage > img').length,0);
 dom.window.close();console.log('OK transiciones: precarga, fundido, fuentes tardías, selección rápida, fallo de imagen y limpieza.');
})().catch(error=>{console.error(error);process.exit(1);});
