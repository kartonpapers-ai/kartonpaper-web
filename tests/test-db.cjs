const {PGlite}=require('@electric-sql/pglite');
const fs=require('fs'),path=require('path'),assert=require('assert/strict');
const root=path.resolve(__dirname,'..');
(async()=>{
 const db=new PGlite();
 await db.exec(`create role anon; create role authenticated; create schema auth; create table auth.users(id uuid primary key); create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$; grant usage on schema auth to anon,authenticated; grant execute on function auth.uid() to anon,authenticated; insert into auth.users values ('11111111-1111-4111-8111-111111111111'),('22222222-2222-4222-8222-222222222222');`);
 await db.exec(fs.readFileSync(path.join(root,'supabase/01-esquema.sql'),'utf8'));
 await db.exec(fs.readFileSync(path.join(root,'supabase/02-productos.sql'),'utf8'));
 await db.exec(`insert into kp_private.admin_user values (1,'11111111-1111-4111-8111-111111111111');`);
 const first=(await db.query('select * from kp_products order by sort_order limit 1')).rows[0];
 await db.exec('set role anon');
 assert.equal((await db.query('select count(*)::integer n from kp_products')).rows[0].n,20);
 await assert.rejects(db.exec(`update kp_products set published=false`));
 await assert.rejects(db.exec('select * from kp_private.admin_user'));
 await db.exec(`reset role; set role authenticated; select set_config('request.jwt.claim.sub','22222222-2222-4222-8222-222222222222',false);`);
 assert.equal((await db.query('select kp_is_admin() allowed')).rows[0].allowed,false);
 assert.equal((await db.query('update kp_products set published=false returning id')).rows.length,0);
 await assert.rejects(db.exec(`insert into kp_private.admin_user values (1,'22222222-2222-4222-8222-222222222222')`));
 await db.exec(`select set_config('request.jwt.claim.sub','11111111-1111-4111-8111-111111111111',false)`);
 assert.equal((await db.query('select kp_is_admin() allowed')).rows[0].allowed,true);
 const updated=await db.query(`update kp_products set data=jsonb_set(data,'{price}','"$999 + IVA c/u"'), published=false where id=$1 and version=1 returning version,data`,[first.id]);
 assert.equal(updated.rows[0].version,2);assert.equal(updated.rows[0].data.price,'$999 + IVA c/u');
 assert.equal((await db.query(`update kp_products set published=true where id=$1 and version=1 returning id`,[first.id])).rows.length,0);
 await assert.rejects(db.exec(`update kp_products set data=jsonb_set(data,'{priceNum}','-10') where id='${first.id}'`));
 await assert.rejects(db.exec(`update kp_products set version=100 where id='${first.id}'`));
 await assert.rejects(db.exec(`delete from kp_products where id='${first.id}'`));
 assert.equal((await db.query('select count(*)::integer n from kp_products')).rows[0].n,20);
 await db.exec('reset role; set role anon');
 assert.equal((await db.query('select count(*)::integer n from kp_products')).rows[0].n,19);
 await db.exec('reset role');
 await db.exec(fs.readFileSync(path.join(root,'supabase/02-productos.sql'),'utf8'));
 assert.equal((await db.query('select version from kp_products where id=$1',[first.id])).rows[0].version,2);
 console.log('OK PostgreSQL: lectura pública, ocultación, administrador único, permisos, validación, conflictos y carga inicial sin sobrescritura.');
 await db.close();
})().catch(e=>{console.error(e);process.exit(1)});
